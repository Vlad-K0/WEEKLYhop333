package com.example.weekly.Presentation

/**
 * Тип элемента, который создаёт пользователь.
 * Определяет, будет ли элемент задачей с временем или обычной заметкой.
 */
enum class NoteType {
    /**
     * Дело - элемент с указанием времени начала.
     * Отображается с Checkbox и временем.
     */
    TASK,
    
    /**
     * Заметка - элемент без времени.
     * Отображается с иконкой Menu.
     */
    NOTE
}
